"""The deterministic pipeline, step by step and end to end.

validate -> record -> captions -> compose -> music -> finalize (+ sheets, storyboard table)

Each step reads what the previous one left in the work directory, so any step can be re-run
alone (re-compose after editing a caption without re-recording, for example).
"""

from __future__ import annotations

import json
import time
from pathlib import Path
from typing import Callable

from . import compose as _compose
from . import finishing as _finalize
from . import graphics, music, sheets
from .errors import StyleViolation
from .paths import default_work_dir, work_layout
from .storyboard import Storyboard, load
from .rules import validate

Log = Callable[[str], None]


def _nolog(_: str) -> None:
    pass


def work_for(sb: Storyboard, work_dir: str | Path | None = None) -> dict[str, Path]:
    wd = Path(work_dir) if work_dir else default_work_dir(sb.path or Path.cwd() / "storyboard.yaml", sb.project.name)
    return work_layout(wd)


def _select(sb: Storyboard, videos: list[str] | None, aspects: list[str] | None):
    vids = [sb.video(v) for v in videos] if videos else list(sb.videos)
    asp = aspects or list(sb.outputs.aspects)
    return vids, asp


def check(sb: Storyboard) -> None:
    rep = validate(sb)
    if not rep.ok:
        raise StyleViolation(f"The storyboard breaks {len(rep.errors)} style rule(s): " + "; ".join(f"{i.where}: {i.message}" for i in rep.errors[:5]),
                             "Fix the listed problems (`teaserkit validate <storyboard>` shows all of them).", details=rep.to_dict())


def render_captions(sb: Storyboard, work: dict[str, Path], *, videos: list[str] | None = None, aspects: list[str] | None = None,
                    force: bool = False, log: Log = _nolog) -> list[Path]:
    vids, asp = _select(sb, videos, aspects)
    items = [it for v in vids for a in asp for it in _compose.graphics_needed(sb, v, a)]
    return graphics.render(items, sb.project.brand, work["gfx"], force=force, log=log)


def compose_videos(sb: Storyboard, work: dict[str, Path], *, videos: list[str] | None = None, aspects: list[str] | None = None,
                   preview: bool = False, log: Log = _nolog) -> list[dict]:
    vids, asp = _select(sb, videos, aspects)
    out = []
    for v in vids:
        for a in asp:
            path = work["silent"] / f"{v.id}-{a}{'-preview' if preview else ''}.mp4"
            out.append(_compose.render_video(sb, v, a, work["raw"], work["gfx"], path, preview=preview, log=log))
    return out


def make_music(sb: Storyboard, work: dict[str, Path], seconds_by_video: dict[str, float], log: Log = _nolog) -> dict[str, dict]:
    if sb.style.get("music") == "none":
        return {}
    res = {}
    for vid, secs in seconds_by_video.items():
        res[vid] = music.make_track(secs, work["audio"] / f"{vid}.wav", bpm=sb.style.get("music_bpm", 96),
                                    seed=int(sb.style.get("music_seed", 7)), progression=sb.style.get("music_progression", "warm"))
        log(f"music for {vid}: {secs:.1f} s")
    return res


def default_poster_at(timeline: list[dict], seconds: float) -> float:
    """Rest on a result: inside the hold of the segment playing at 40% of the video."""
    target = 0.4 * seconds
    for seg in timeline:
        if seg["start"] <= target < seg["start"] + seg["seconds"]:
            return round(max(seg["start"], seg["start"] + seg["seconds"] - 0.8), 2)
    return round(target, 2)


def storyboard_table(sb: Storyboard, composed: list[dict]) -> str:
    lines = [f"# {sb.project.name}: teaser storyboard", "", "Generated by teaserkit. Timings are from the 16:9 render; other aspects share them.", ""]
    shown = set()
    for c in composed:
        if c["video"] in shown:
            continue
        shown.add(c["video"])
        v = sb.video(c["video"])
        beats = {b.id: b for b in v.beats}
        lines += [f"## {v.id} ({v.kind}, {c['seconds']:.1f} s)", "", "| Time | Segment | Caption |", "| --- | --- | --- |"]
        for seg in c["timeline"]:
            b = beats.get(seg["id"])
            if b:
                cap = " / ".join(b.caption_lines())
            elif seg["id"] == "title":
                cap = (v.title or {}).get("title", "")
            else:
                cap = (v.end or {}).get("tagline", "")
            lines.append(f"| {seg['start']:.1f}-{seg['start'] + seg['seconds']:.1f} | {seg['id']} | {cap.replace(chr(10), ' ')} |")
        lines.append("")
    return "\n".join(lines)


def build(storyboard: str | Path | Storyboard, out_dir: str | Path, *, work_dir: str | Path | None = None,
          videos: list[str] | None = None, aspects: list[str] | None = None, preview: bool = False,
          skip_record: bool = False, log: Log | None = None) -> dict:
    """Run the whole deterministic pipeline. Returns a summary with every artifact path.

    No model provider is needed. Raises StyleViolation before recording if the storyboard breaks
    a style rule, LeakDetected if a deny-listed string appears on screen.
    """
    from . import recorder as _record

    log = log or _nolog
    t_start = time.time()
    sb = storyboard if isinstance(storyboard, Storyboard) else load(storyboard)
    check(sb)
    work = work_for(sb, work_dir)
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    vids, asp = _select(sb, videos, aspects)
    log(f"work directory: {work['root']}")
    takes = []
    if not skip_record:
        needed = sorted({b.take for v in vids for b in v.beats})
        takes = [t.__dict__ for t in _record.record(sb, work["raw"], takes=needed, log=log)]
    render_captions(sb, work, videos=[v.id for v in vids], aspects=asp, log=log)
    composed = compose_videos(sb, work, videos=[v.id for v in vids], aspects=asp, preview=preview, log=log)
    secs = {}
    for c in composed:
        secs.setdefault(c["video"], c["seconds"])
    tracks = make_music(sb, work, secs, log)
    st = sb.style
    results = []
    for c in composed:
        v = sb.video(c["video"])
        name = f"{v.id}-{c['aspect']}{'-preview' if preview else ''}"
        at = v.poster_at if v.poster_at is not None else default_poster_at(c["timeline"], c["seconds"])
        no_audio = sb.outputs.no_audio == "all" or (sb.outputs.no_audio == "main" and v.kind == "main")
        wav = tracks.get(v.id, {}).get("path")
        r = _finalize.finalize(c["path"], wav, out, name, poster_at=at if sb.outputs.posters else None, no_audio=no_audio,
                               lufs=st["loudness_lufs"], tp=st["true_peak_db"], lra=st["loudness_range"])
        r["probe"] = _finalize.probe(r["video"])
        if sb.outputs.sheets:
            r["sheet"] = sheets.contact_sheet(r["video"], out / "sheets" / f"{name}.png")["path"]
        r.update({"id": v.id, "aspect": c["aspect"], "seconds": c["seconds"], "poster_at": at if sb.outputs.posters else None})
        results.append(r)
        log(f"finished {name}: {r['probe']['seconds']} s")
    table = out / "STORYBOARD.md"
    table.write_text(storyboard_table(sb, composed))
    summary = {
        "ok": True,
        "project": sb.project.name,
        "out_dir": str(out.resolve()),
        "work_dir": str(work["root"]),
        "takes": [{k: str(v) if isinstance(v, Path) else v for k, v in t.items()} for t in takes],
        "outputs": results,
        "storyboard_table": str(table),
        "elapsed_seconds": round(time.time() - t_start, 1),
    }
    (out / "build.json").write_text(json.dumps(summary, indent=1))
    return summary
